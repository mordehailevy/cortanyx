-- =============================================================
--  ChatGPT Clone - MySQL schema
--  Author: Mordehai Levy
--
--  Two tables:
--    conversations : one row per conversation (unique UUID id)
--    messages      : one row per message, linked to its conversation,
--                    with a `role` column saying WHO wrote it
--                    ('user' = the human, 'assistant' = the chat)
--
--  utf8mb4 everywhere so Hebrew, French and emoji are stored safely.
-- =============================================================

CREATE DATABASE IF NOT EXISTS chatgpt_clone
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE chatgpt_clone;

DROP VIEW  IF EXISTS v_conversation_messages;
DROP TABLE IF EXISTS usage_log;
DROP TABLE IF EXISTS messages;
DROP TABLE IF EXISTS conversations;

CREATE TABLE conversations (
  id          CHAR(36)     NOT NULL COMMENT 'Unique conversation id (UUID v4)',
  title       VARCHAR(120) NOT NULL DEFAULT 'New conversation' COMMENT 'Short title, generated by the AI after the first exchange',
  model       VARCHAR(64)  NOT NULL COMMENT 'OpenAI model used for this conversation',
  pinned      BOOLEAN      NOT NULL DEFAULT FALSE COMMENT 'Pinned (starred) conversations are listed first',
  pin_order   INT          NULL COMMENT 'Position among pinned conversations (sidebar drag and drop)',
  created_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT 'Last message time (not changed by rename / pin)',
  PRIMARY KEY (id),
  KEY idx_conversations_list (pinned, pin_order, updated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='One row per chat conversation';

CREATE TABLE messages (
  id               BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  conversation_id  CHAR(36)        NOT NULL COMMENT 'Conversation this message belongs to',
  role             ENUM('user','assistant') NOT NULL COMMENT 'user = written by the human, assistant = written by the chat',
  content          MEDIUMTEXT      NOT NULL,
  tokens           INT UNSIGNED    NULL COMMENT 'Tokens reported by OpenAI (assistant messages only)',
  interrupted      BOOLEAN         NOT NULL DEFAULT FALSE COMMENT 'Answer stopped before its end (Stop button / page closed)',
  created_at       DATETIME(3)     NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_messages_conversation (conversation_id, id),
  KEY idx_messages_created (created_at),
  CONSTRAINT fk_messages_conversation
    FOREIGN KEY (conversation_id) REFERENCES conversations (id)
    ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Every message of every conversation, in order';

-- One row per OpenAI call. Not linked to conversations on purpose: deleting a
-- conversation must not reset the daily token budget computed from this table.
CREATE TABLE usage_log (
  id          BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  kind        VARCHAR(16)  NOT NULL COMMENT 'answer, regenerate, title or interrupted',
  tokens      INT UNSIGNED NOT NULL COMMENT 'Tokens reported by OpenAI, or estimated (4 characters per token)',
  created_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY idx_usage_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
  COMMENT='Spending log used by the daily token budget';

-- Human-readable view: anyone browsing the DB sees at a glance
-- which conversation, who spoke (User / ChatGPT) and what was said.
CREATE VIEW v_conversation_messages AS
SELECT
  c.id                                   AS conversation_id,
  c.title                                AS conversation_title,
  m.id                                   AS message_id,
  CASE m.role WHEN 'user' THEN 'User' ELSE 'ChatGPT' END AS sender,
  m.content                              AS content,
  m.created_at                           AS sent_at
FROM messages m
JOIN conversations c ON c.id = m.conversation_id
ORDER BY c.created_at, m.id;
